'use strict';

// Regenerates src/ae/grad-canonical.jsx from a canonical AE-saved gradient
// preset (test/e2e/out/probe-canonical.ffx). The canonical file is an
// AE 2026 "Save Animation Preset" of a shape-layer Gradient Fill group;
// at runtime we splice generated stop XML into its Utf8 chunk and patch
// the ancestor chunk sizes.
//
// Usage: node tools/gen-grad-template.js [path-to-canonical.ffx]

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const src = process.argv[2] || path.join(ROOT, 'test', 'e2e', 'out', 'probe-canonical.ffx');
const buf = fs.readFileSync(src);

// sanity: verify RIFX structure and locate the gradient XML
if (buf.toString('latin1', 0, 4) !== 'RIFX') throw new Error('not a RIFX file');
const xmlStart = buf.indexOf('<prop.map');
const xmlEnd = buf.indexOf('</prop.map>', xmlStart) + '</prop.map>'.length;
if (xmlStart === -1) throw new Error('no gradient prop.map found');

// verify the ancestor chain is discoverable by a runtime walk
function findChain(off, end, target, chain) {
  while (off + 8 <= end) {
    const id = buf.toString('latin1', off, off + 4);
    const size = buf.readUInt32BE(off + 4);
    const dataStart = off + 8;
    const dataEnd = dataStart + size;
    if (target >= dataStart && target < dataEnd) {
      chain.push({ id, sizeOffset: off + 4, size });
      if (id === 'RIFX' || id === 'LIST') {
        findChain(dataStart + 4, dataEnd, target, chain);
      }
      return chain;
    }
    off = dataEnd + (size % 2);
  }
  return chain;
}
const chain = findChain(0, buf.length, xmlStart, []);
console.log('ancestor chain:', chain.map((c) => c.id + '@' + (c.sizeOffset - 4)).join(' > '));
const leaf = chain[chain.length - 1];
if (buf.toString('latin1', leaf.sizeOffset - 4, leaf.sizeOffset) !== 'Utf8') {
  throw new Error('expected XML inside a Utf8 chunk, got ' + leaf.id);
}

// escape bytes to a compact JS string literal (latin1-safe)
function escapeByteString(b) {
  let out = '';
  for (const byte of b) {
    if (byte === 0x5c) out += '\\\\';
    else if (byte === 0x22) out += '\\"';
    else if (byte === 0x0a) out += '\\n';
    else if (byte === 0x0d) out += '\\r';
    else if (byte === 0x09) out += '\\t';
    else if (byte >= 0x20 && byte < 0x7f) out += String.fromCharCode(byte);
    else out += '\\u' + byte.toString(16).padStart(4, '0').toUpperCase();
  }
  return out;
}

const head = buf.subarray(0, xmlStart);
const tail = buf.subarray(xmlEnd);

const lines = [];
lines.push('// Canonical AE 2026 gradient-fill preset (Save Animation Preset of a');
lines.push('// G-Fill group), split around its Gradient Color Data XML. Generated by');
lines.push('// tools/gen-grad-template.js - do not edit by hand.');
lines.push('');
lines.push('var SVGSPLIT = SVGSPLIT || {};');
lines.push('');
lines.push('SVGSPLIT.gradCanonical = {');
lines.push('  head: "' + escapeByteString(head) + '",');
lines.push('  tail: "' + escapeByteString(tail) + '",');
lines.push('  xmlLength: ' + (xmlEnd - xmlStart));
lines.push('};');
lines.push('');

const outPath = path.join(ROOT, 'src', 'ae', 'grad-canonical.jsx');
fs.writeFileSync(outPath, lines.join('\n'));
console.log('wrote', outPath, '(head', head.length, 'bytes, tail', tail.length, 'bytes, xml', xmlEnd - xmlStart, 'bytes)');
